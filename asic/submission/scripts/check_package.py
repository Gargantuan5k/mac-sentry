#!/usr/bin/env python3
"""Check exported inventory and the physical contract; no Git or agent dependency."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def check(root=ROOT, ci=False):
    root = Path(root)
    manifest = json.loads((root / 'PACKAGE_MANIFEST.json').read_text())
    if manifest.get('schema') != 1 or not manifest.get('files'):
        raise ValueError('Missing package inventory')
    for name, expected in manifest['files'].items():
        rel = Path(name)
        if rel.is_absolute() or '..' in rel.parts or not rel.parts:
            raise ValueError('Unsafe inventory path')
        path = root / rel
        if path.is_symlink() or not path.resolve().is_relative_to(root.resolve()):
            raise ValueError('Unsafe package member: ' + name)
        if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
            raise ValueError('Package identity changed: ' + name)
    info = json.loads((root / 'info.yaml').read_text())
    project = info['project']
    if (info['yaml_version'] != 6 or project['top_module'] != 'tt_um_mac_sentry'
            or project['tiles'] != '2x2' or project['clock_hz'] != 20000000):
        raise ValueError('Incorrect project metadata')
    expected_sources = ['secded_encoder.sv', 'secded_decoder.sv', 'signed_residue7.sv',
        'mac_residue7_check.sv', 'mac_hybrid.sv', 'tt_um_mac_sentry.sv']
    if project['source_files'] != expected_sources:
        raise ValueError('Production source list changed')
    expected_pins = {f'{port}[{i}]' for port in ('ui', 'uo', 'uio') for i in range(8)}
    if set(info['pinout']) != expected_pins:
        raise ValueError('Pin metadata mismatch')
    contract = json.loads((root / 'flow_contract.json').read_text())
    config = json.loads((root / ('src/config_merged.json' if ci else 'src/config.json')).read_text())
    for key, value in contract.items():
        if key in ('DIE_AREA', 'DESIGN_NAME') and not ci:
            continue  # Generated by the official support tools, checked after merge.
        actual = config.get(key)
        if key == 'DIE_AREA' and isinstance(actual, str):
            actual = [float(x) for x in actual.split()]
        if key in ('PNR_SDC_FILE', 'SIGNOFF_SDC_FILE'):
            actual = str(actual).split('::')[-1].split('/')[-1]
        if actual != value:
            raise ValueError(f'Physical configuration drift: {key}: {actual!r} != {value!r}')
    if ci:
        if config.get('VERILOG_FILES') != ['dir::' + n for n in expected_sources]:
            raise ValueError('Merged source list mismatch')
        if Path(config.get('FP_DEF_TEMPLATE', '')).name != 'tt_block_2x2_pg.def':
            raise ValueError('Merged floorplan mismatch')
        pdk = json.loads((root / 'tt_submission/pdk.json').read_text())
        lock = json.loads((root / 'requirements/asic-lock.json').read_text())
        if (pdk.get('PDK') != 'sky130A' or pdk.get('PDK_VERSION') != lock['hardening_pdk']
                or pdk.get('FLOW_VERSION') != lock['librelane_version']):
            raise ValueError('CI tool or PDK identity differs from the local baseline')
    return {'status': 'PASS', 'checks': 'inventory, production metadata, physical contract',
            'ci_configuration_checked': ci, 'signoff': False}


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--ci-config', action='store_true')
    args = p.parse_args()
    print(json.dumps(check(ci=args.ci_config)))
